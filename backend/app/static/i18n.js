export const LANGUAGES = [
  { id: "tr", label: "Türkçe" },
  { id: "en", label: "English" },
  { id: "de", label: "Deutsch" },
  { id: "fr", label: "Français" },
  { id: "es", label: "Español" },
  { id: "pt", label: "Português" },
  { id: "ru", label: "Русский" },
  { id: "ar", label: "العربية", rtl: true },
  { id: "zh", label: "中文" },
];

let current = localStorage.getItem("vq_lang")
  || (navigator.language || "tr").slice(0, 2).toLowerCase();
if (!DICT[current]) current = "tr";

/** Etkin dil kodu. Ajana da bu iletilir. */
export function lang() {
  return current;
}

/** Çeviri. Anahtar yoksa Türkçeye, o da yoksa anahtarın kendisine düşer. */
export function t(key, vars = {}) {
  const text = DICT[current]?.[key] ?? DICT.tr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? `{${name}}`);
}

/** `data-i18n` ve `data-i18n-attr` taşıyan her düğümü doldurur. */
export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.innerHTML = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    // biçim: data-i18n-attr="placeholder:home.placeholder,title:nav.search"
    node.dataset.i18nAttr.split(",").forEach((pair) => {
      const [attr, key] = pair.split(":").map((x) => x.trim());
      if (attr && key) node.setAttribute(attr, t(key));
    });
  });
  document.documentElement.lang = current;

  // Sağdan sola yazılan diller (Arapça) için yön değiştirilir; düzen aynalanır.
  const meta = LANGUAGES.find((l) => l.id === current);
  document.documentElement.dir = meta?.rtl ? "rtl" : "ltr";
}

/** Dili değiştirir ve arayüzü yeniden çizer. */
export function setLang(code) {
  if (!DICT[code] || code === current) return;
  current = code;
  localStorage.setItem("vq_lang", code);
  applyI18n(document);
  window.VQ?.render?.();
}
